import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { PluginManager } from '../../dist/main/plugins/manager.js';
import { AgentHost } from '../../dist/main/agent/agent-host.js';
import { createWorkspaceTools } from '../../dist/main/workspace/permissions.js';
import { setupFixture } from '../support/fixture.mjs';
import { createInstallFixture } from '../support/install-fixture.mjs';

test('installed Pi package and Skill execute through real Agent; skill assets stay read-only', async (t) => {
  const fixture = await setupFixture();
  const host = new AgentHost(() => {}, () => {}, fixture.agentDir);
  t.after(async () => { await host.dispose(); fixture.close(); });
  const { packageDir, skillDir } = await createInstallFixture(fixture);
  const plugins = new PluginManager(fixture.agentDir, fixture.project);
  await assert.rejects(plugins.install('', 'package'), /有效/);
  await assert.rejects(plugins.install(fixture.project, 'skill'), /ENOENT|SKILL/);
  await plugins.install(packageDir, 'package');
  const inventory = await plugins.install(skillDir, 'skill');
  assert.equal(inventory.packages.find((item) => item.source.endsWith('local-pi-package'))?.installed, true);
  assert.ok(inventory.skills.some((item) => item.name === 'installed-skill'));
  const view = await host.create(fixture.project, true);
  assert.ok(view.extensions.includes(join(packageDir, 'index.ts')));
  assert.ok(view.skills.some((item) => item.name === 'installed-skill'));
  await host.send(view.id, 'INSTALLED_PLUGIN_TOOL', [], []);
  assert.equal(await readFile(join(fixture.project, 'installed-plugin-proof.txt'), 'utf8'), 'INSTALLED_PLUGIN_EXECUTED');
  assert.match(JSON.stringify(fixture.state.payloads.at(-1)), /INSTALL_SKILL_DESCRIPTION/);
  await host.send(view.id, '/skill:installed-skill SKILL_INVOKED', [], []);
  assert.match(fixture.state.instructions.at(-1), /SKILL_INSTALL_PROOF/);
  assert.match(fixture.state.instructions.at(-1), /SKILL_INVOKED/);
  await assert.rejects(host.send(view.id, '/skill:missing-name', [], []), /未找到 Skill/);
  fixture.state.skillPath = join(skillDir, 'SKILL.md');
  await host.send(view.id, 'READ_INSTALLED_SKILL', [], []);
  assert.match(JSON.stringify(fixture.state.toolResults.at(-1)), /SKILL_INSTALL_PROOF/);
  const tools = await createWorkspaceTools(fixture.project, 'workspace', [skillDir]);
  const read = tools.find((tool) => tool.name === 'read');
  const write = tools.find((tool) => tool.name === 'write');
  assert.match(JSON.stringify(await read.execute('reference', { path: join(skillDir, 'reference.txt') })), /SKILL_REFERENCE_PROOF/);
  await assert.rejects(write.execute('write-skill', { path: join(skillDir, 'reference.txt'), content: 'forbidden' }), /权限/);
  await assert.rejects(read.execute('read-config', { path: join(fixture.agentDir, 'auth.json') }), /权限/);
  await host.dispose();
  const restarted = new AgentHost(() => {}, () => {}, fixture.agentDir);
  t.after(() => restarted.dispose());
  const resumed = await restarted.open(view.id, async () => true);
  assert.ok(resumed.skills.some((item) => item.name === 'installed-skill'));
  assert.ok(resumed.extensions.includes(join(packageDir, 'index.ts')));
});
