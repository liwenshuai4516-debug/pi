import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { AgentHost } from '../../dist/main/agent/agent-host.js';
import { setupFixture, until } from '../support/fixture.mjs';
import { createMcpFixture } from '../support/mcp-fixture.mjs';

test('MCP management persists file config, controls native tools, preserves unrelated settings and never returns secrets', async t => {
  const fixture = await setupFixture(), server = await createMcpFixture();
  const host = new AgentHost(() => {}, () => {}, fixture.agentDir);
  t.after(async () => { await host.dispose(); await server.close(); fixture.close(); });
  const path = join(fixture.agentDir, 'mcp.json');
  await writeFile(path, JSON.stringify({ custom: 'preserved', mcpServers: {} }));
  await mkdir(join(fixture.agentDir, 'extensions'));
  await writeFile(join(fixture.agentDir, 'extensions/lifecycle.js'), `import {appendFileSync} from 'node:fs'; export default pi => pi.on('session_start', (_, ctx) => appendFileSync(ctx.cwd + '/starts.txt', 'start'));`);
  const view = await host.create(fixture.project, true);
  assert.equal((await host.listMcp(view.id)).available, true);
  await assert.rejects(host.addMcp(view.id, 'bad.name', JSON.stringify({url: server.url})), /name|Name|invalid|Invalid/);
  await assert.rejects(host.addMcp(view.id, 'bad', '{"token":"INPUT_SECRET"'), /有效的 JSON/);
  await assert.rejects(host.addMcp(view.id, 'bad', '{}'), /command|url|URL/);
  await host.addMcp(view.id, 'postman', JSON.stringify({ url: server.url, headers: { Authorization: 'Bearer MCP_SECRET' }, exposure: 'direct' }));
  await until(async () => (await host.listMcp(view.id)).servers[0]?.state === 'connected');
  const inventory = await host.listMcp(view.id);
  assert.equal(inventory.servers[0].scope, 'global');
  assert.equal(inventory.servers[0].tools.length, 1);
  assert.doesNotMatch(JSON.stringify(inventory), /MCP_SECRET|Authorization/);
  const activeNames = () => host.entries.get(view.id).agent.state.tools.map(tool => tool.name);
  assert.ok(activeNames().includes('mcp__postman__echo'));
  await host.send(view.id, 'MCP_DIRECT_PROOF', [], []);
  assert.equal(server.calls, 1);
  await host.manageMcp(view.id, 'postman', 'disable');
  assert.equal((await host.listMcp(view.id)).servers[0].state, 'disabled');
  assert.ok(!activeNames().includes('mcp__postman__echo'));
  await host.manageMcp(view.id, 'postman', 'enable');
  await until(async () => (await host.listMcp(view.id)).servers[0]?.state === 'connected');
  await host.manageMcp(view.id, 'postman', 'hidden');
  await until(async () => (await host.listMcp(view.id)).servers[0]?.state === 'connected');
  assert.ok(!activeNames().includes('mcp__postman__echo'));
  assert.equal(JSON.parse(await readFile(path, 'utf8')).mcpServers.postman.exposure, 'hidden');
  await host.manageMcp(view.id, 'postman', 'direct');
  await until(() => activeNames().includes('mcp__postman__echo'));
  const config = JSON.parse(await readFile(path, 'utf8'));
  assert.equal(config.custom, 'preserved');
  assert.equal(config.mcpServers.postman.headers.Authorization, 'Bearer MCP_SECRET');
  await host.manageMcp(view.id, 'postman', 'remove');
  assert.equal((await host.listMcp(view.id)).servers.length, 0);
  assert.ok(!activeNames().includes('mcp__postman__echo'));
  assert.equal(JSON.parse(await readFile(path, 'utf8')).custom, 'preserved');
  assert.equal(await readFile(join(fixture.project, 'starts.txt'), 'utf8'), 'start');
});

test('extension MCP changes are session-only; project trust and disabled builtin are respected', async t => {
  const fixture = await setupFixture(), server = await createMcpFixture();
  const host = new AgentHost(() => {}, () => {}, fixture.agentDir);
  t.after(async () => { await host.dispose(); await server.close(); fixture.close(); });
  await mkdir(join(fixture.agentDir, 'extensions'));
  await writeFile(join(fixture.agentDir, 'extensions/service.js'), `export default pi => pi.registerMcpServer('registered', {url: ${JSON.stringify(server.url)}});`);
  await mkdir(join(fixture.project, '.pi'));
  await writeFile(join(fixture.project, '.pi/mcp.json'), JSON.stringify({mcpServers: {project: {url: server.url, enabled: false}}}));
  const view = await host.create(fixture.project, false);
  await until(async () => (await host.listMcp(view.id)).servers[0]?.state === 'connected');
  assert.equal((await host.listMcp(view.id)).servers.length, 1);
  await host.manageMcp(view.id, 'registered', 'disable');
  await until(async () => (await host.listMcp(view.id)).servers[0]?.state === 'disabled');
  assert.equal((await host.listMcp(view.id)).servers[0].scope, 'extension');
  await assert.rejects(readFile(join(fixture.agentDir, 'mcp.json')), {code: 'ENOENT'});
  await assert.rejects(host.manageMcp(view.id, 'registered', 'remove'), /扩展/);
  const trusted = await host.create(fixture.project, true);
  assert.equal((await host.listMcp(trusted.id)).servers.find(item => item.name === 'project').scope, 'project');
  await until(async () => (await host.listMcp(trusted.id)).servers.find(item => item.name === 'registered')?.state === 'connected');
  const settingsPath = join(fixture.agentDir, 'settings.json');
  const settings = JSON.parse(await readFile(settingsPath, 'utf8'));
  await writeFile(settingsPath, JSON.stringify({...settings, extensions: ['-builtin:mcp']}));
  const disabled = await host.create(fixture.project, false);
  assert.equal((await host.listMcp(disabled.id)).available, false);
  await assert.rejects(host.addMcp(disabled.id, 'test', JSON.stringify({url: server.url})), /MCP/);
});
