import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir, writeFile, readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {AgentHost} from '../../dist/main/agent/agent-host.js';
import {describeInChinese} from '../../dist/shared/descriptions-zh.js';
import {setupFixture} from '../support/fixture.mjs';

test('Chinese descriptions support search without changing commands, source resources or model context', async t => {
  const fixture = await setupFixture();
  const host = new AgentHost(() => {}, () => {}, fixture.agentDir);
  t.after(async () => {await host.dispose(); fixture.close();});
  for (const dir of ['extensions', 'prompts', 'skills/council-mode']) await mkdir(join(fixture.agentDir, dir), {recursive:true});
  const commandDescription = 'Toggle or configure the search curator workflow';
  await writeFile(join(fixture.agentDir, 'extensions/curator.js'), `export default pi => pi.registerCommand('curator', {description:${JSON.stringify(commandDescription)}, handler:()=>{}});`);
  await writeFile(join(fixture.agentDir, 'prompts/council.md'), '---\ndescription: Run a bounded supervisor-mediated council of advisors and write a decision memo\n---\nORIGINAL_TEMPLATE $ARGUMENTS');
  const skillDescription = 'Run a bounded supervisor-mediated advisor council. Use when the user asks for council mode, asks to convene advisors, debate a decision, cross-examine recommendations, or run /council.';
  const skillPath = join(fixture.agentDir, 'skills/council-mode/SKILL.md');
  const skillSource = `---\nname: council-mode\ndescription: ${skillDescription}\n---\nORIGINAL_SKILL_CONTENT`;
  await writeFile(skillPath, skillSource);
  const view = await host.create(fixture.project, true);
  const all = await host.complete(view.id, '/');
  for (const item of all) assert.match(item.description, /[\u3400-\u9fff]/);
  assert.equal(all.find(item => item.value === '/curator ').description, '开启、关闭或配置搜索结果整理工作流');
  assert.equal((await host.complete(view.id, '/整理'))[0].value, '/curator ');
  assert.equal((await host.complete(view.id, '/Toggle'))[0].value, '/curator ', 'original description remains searchable');
  assert.ok((await host.complete(view.id, '/决策')).some(item => item.value === '/council '));
  assert.equal((await host.complete(view.id, '/mcp'))[0].value, '/mcp ');
  assert.equal(fixture.state.requests, 0, 'localization does not invoke a model or translation service');
  await host.send(view.id, '/skill:council-mode CHECK_LOCALIZATION', [], []);
  assert.match(JSON.stringify(fixture.state.payloads.at(-1)), /Run a bounded supervisor-mediated advisor council/);
  assert.match(JSON.stringify(fixture.state.payloads.at(-1)), /ORIGINAL_SKILL_CONTENT/);
  assert.equal(await readFile(skillPath, 'utf8'), skillSource);
  assert.equal(describeInChinese('Use subagents to gather context,\n then ask clarifying questions'), '使用子代理收集上下文，再提出澄清问题');
  assert.equal(describeInChinese('用户自定义中文说明'), '用户自定义中文说明');
  assert.equal(describeInChinese('Unknown custom description'), 'Unknown custom description', 'unknown third-party text is preserved rather than guessed');
  assert.equal(describeInChinese('__proto__'), '__proto__');
  assert.equal(describeInChinese('connected · 3 tools · resources'), '已连接 · 3 个工具 · 资源');
});
